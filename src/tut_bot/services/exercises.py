def _infer_unit_id(ex: Exercise) -> str:
    """Infiere la unidad curricular temática de Goethe/Cambridge a partir del contenido del ejercicio."""
    if ex.unit_id:
        return ex.unit_id
    cat = (ex.category or "").lower()
    title = (ex.title or "").lower()
    text = (ex.target_text or "").lower()
    full = f"{cat} {title} {text}"
    if any(k in full for k in ["einkauf", "preis", "essen", "trink", "kaffee", "kost", "food", "drink", "order", "bill", "restaurant", "croissant"]):
        return "unit_2"
    if any(k in full for k in ["familie", "eltern", "bruder", "schwester", "family", "friend", "sister", "brother", "mother", "father", "roommate"]):
        return "unit_3"
    if any(k in full for k in ["uhr", "zeit", "alltag", "wohnung", "time", "clock", "house", "room", "routine", "aufstehen", "wake"]):
        return "unit_4"
    if any(k in full for k in ["stadt", "zug", "bahn", "bus", "weg", "city", "train", "station", "direction", "verkehr", "gleis", "airport"]):
        return "unit_5"
    if any(k in full for k in ["wetter", "gesund", "arzt", "krank", "sport", "weather", "health", "hobby", "freizeit", "kopfschmerz", "pharmacy", "doctor"]):
        return "unit_6"
    return "unit_1"


def get_exercises(
    language: Optional[str] = None,
    category: Optional[str] = None,
    level: Optional[str] = None,
    skill_type: Optional[str] = None,
    unit_id: Optional[str] = None,
) -> List[Exercise]:
    results = EXERCISES_DATABASE
    if language:
        results = [e for e in results if e.language.lower() == language.lower()]
    if category:
        results = [e for e in results if e.category.lower() == category.lower()]
    if level:
        results = [e for e in results if e.level.lower() == level.lower()]
    if skill_type:
        target_skill = (
            "listening"
            if skill_type.lower() in ("listening", "comprehension")
            else skill_type.lower()
        )
        results = [e for e in results if (e.skill_type or "speaking").lower() == target_skill]
    if unit_id and unit_id.lower() != "all":
        norm_unit = f"unit_{unit_id}" if str(unit_id).isdigit() else unit_id.lower()
        if norm_unit.startswith("sel_"):
            clean = norm_unit.replace("sel_", "")
            norm_unit = f"unit_{clean}" if clean.isdigit() else clean
        filtered = [e for e in results if (e.unit_id or _infer_unit_id(e)).lower() == norm_unit]
        return filtered
    return results


def get_categories(language: str) -> List[str]:
    seen = set()
    categories = []
    for e in EXERCISES_DATABASE:
        if e.language.lower() == language.lower() and e.category not in seen:
            seen.add(e.category)
            categories.append(e.category)
    return categories
